// Builds doc.html, the page customers open from an estimate or invoice link.
// It reuses the document renderer and styles from index.html so the two always match.
// Runs as part of `npm run build`; commit the generated doc.html so GitHub Pages serves it.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('index.html', 'utf8');
const grab = (re, what) => { const m = src.match(re); if (!m) throw new Error('build-doc: could not find ' + what); return m[0]; };
const code = [
  grab(/const esc=v=>[^\n]*/, 'esc'), grab(/const num=v=>[^\n]*/, 'num'), grab(/const sum=\(a,f=x=>x\)=>[^\n]*/, 'sum'),
  grab(/const money2=n=>[^\n]*/, 'money2'), grab(/const pd=[^\n]*/, 'pd'), grab(/const fmtDateY=[^\n]*/, 'fmtDateY'),
  'const job=()=>null;', grab(/const DOC_KIND=[^\n]*/, 'DOC_KIND'), grab(/function docTotals\(d\)\{[\s\S]*?return\{sub,tax,total,paid,balance:total-paid\}\}/, 'docTotals'),
  grab(/function docHTML\(d,co\)\{[\s\S]*?<\/article>`\}/, 'docHTML'),
].join('\n');
const css = grab(/\/\* estimates & invoices \*\/[\s\S]*?\.doc-ok\{[^}]*\}/, 'document styles');
const sb = grab(/const SB_URL='[^']+',SB_KEY='[^']+';/, 'Supabase settings');

const html = `<!doctype html>
<!-- Generated by scripts/build-doc.mjs from index.html. Edit those, not this file. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex"><title>Blue Board</title><link rel="icon" href="icons/icon.svg">
<style>
@font-face{font-family:'Manrope';font-weight:400 800;font-display:swap;src:url(vendor/manrope.woff2) format('woff2')}
@font-face{font-family:'DM Sans';font-weight:400 700;font-display:swap;src:url(vendor/dmsans.woff2) format('woff2')}
:root{--bg:#F4F6FF;--surface:#fff;--surface2:#eef1fb;--ink:#10142B;--muted:#5b6280;--line:rgba(16,20,43,.08);--line2:rgba(16,20,43,.14);--hi:#2D5BFF;--good:#127a3d;--good-bg:#e5f6ec;--bad:#c42b2b;--bad-bg:#fdeceb;--warn:#9a5b00;--warn-bg:#fff4dc}
@media (prefers-color-scheme:dark){:root{--bg:#0B0E1F;--surface:#151A33;--surface2:#1d2342;--ink:#EEF1FF;--muted:#A3AACB;--line:rgba(255,255,255,.08);--line2:rgba(255,255,255,.14);--hi:#7C9BFF}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--ink);font:15px/1.5 'DM Sans',system-ui,sans-serif}
main{max-width:820px;margin:0 auto;padding:24px 16px 64px}
.bar{display:flex;gap:10px;flex-wrap:wrap;align-items:center;justify-content:space-between;margin-bottom:14px}
.bar h1{font:800 20px/1.2 Manrope,sans-serif;margin:0}
.btn{appearance:none;border:0;border-radius:999px;padding:11px 18px;font:700 14px 'DM Sans',sans-serif;cursor:pointer;background:var(--surface2);color:var(--ink)}
.btn.primary{background:linear-gradient(135deg,#2D5BFF,#00A8F0);color:#fff}.btn.ghost{background:transparent}.btn:disabled{opacity:.6}
.card{background:var(--surface);border:1px solid var(--line);border-radius:24px;padding:18px;margin-top:14px}
.card h2{font:800 17px Manrope,sans-serif;margin:0 0 8px}input{width:100%;padding:12px 14px;border-radius:14px;border:1px solid var(--line2);background:var(--bg);color:var(--ink);font:inherit;margin:6px 0 12px}
.row{display:flex;gap:10px;flex-wrap:wrap}.note{color:var(--muted);font-size:13px}.ok{color:var(--good);font-weight:700}.err{color:var(--bad)}
.doc-wrap{border:1px solid var(--line2);border-radius:18px;overflow:hidden;box-shadow:0 10px 30px -10px rgba(16,24,40,.18)}
footer{margin-top:22px;text-align:center;font-size:12.5px;color:var(--muted)}footer a{color:inherit}
${css}
@media print{body{background:#fff}.bar,.card,footer{display:none!important}main{padding:0;max-width:none}.doc-wrap{border:0;box-shadow:none;border-radius:0}}
</style></head>
<body><main><div id="app"><p class="note">Loading…</p></div>
<footer>Sent with <a href="https://getblueboard.com/">Blue Board</a></footer></main>
<script src="vendor/supabase.js"></script>
<script>
${code}
${sb}
const $=s=>document.querySelector(s),app=$('#app'),token=(location.hash||'').slice(1).replace(/[^a-f0-9]/gi,'');
const sbc=window.supabase.createClient(SB_URL,SB_KEY,{auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false}});
const STATUS={approved:'Approved',declined:'Declined',paid:'Paid'};
async function load(){if(!token){app.innerHTML='<p class="err">This link is missing part of its address. Ask the sender to send it again.</p>';return}
  const {data,error}=await sbc.rpc('get_shared_doc',{p_token:token});
  if(error||!data){app.innerHTML='<p class="err">This document wasn\\'t found. It may have been withdrawn. Ask the sender for a new link.</p>';return}
  render(data)}
function render(r){const d=r.data,est=d.kind==='estimate',t=docTotals(d),st=r.status,co=d.company||{};
  document.title=DOC_KIND[d.kind]+' '+d.num+(co.company?' · '+co.company:'');
  const decided=st==='approved'||st==='declined';
  app.innerHTML=\`<div class="bar"><h1>\${esc(DOC_KIND[d.kind]+' '+d.num)}</h1><button class="btn" id="print">Print or save PDF</button></div>
    \${est?\`<div class="card" id="respond">\${decided?(st==='approved'?\`<p class="ok">Approved\${r.approved_name?' by '+esc(r.approved_name):''}. Thank you!</p>\`:'<p class="note">You declined this estimate. Contact us if you change your mind.</p>')
      :\`<h2>Approve this estimate</h2><p class="note">Total \${money2(t.total)}. Type your name and tap Approve to accept it. \${esc(co.company||'The contractor')} will be notified.</p>
        <input id="who" placeholder="Your full name" autocomplete="name"><div class="row"><button class="btn primary" id="approve">Approve estimate</button><button class="btn ghost" id="decline">Decline</button></div><p class="note err" id="msg" hidden></p>\`}</div>\`
      :(d.st==='paid'?'<div class="card"><p class="ok">Paid in full. Thank you!</p></div>':\`<div class="card"><h2>Amount due: \${money2(Math.max(0,t.balance))}</h2><p class="note">\${d.due?'Due '+fmtDateY(d.due)+'. ':''}Contact \${esc(co.company||'us')}\${co.phone?' at '+esc(co.phone):''} with any questions about this invoice.</p></div>\`)}
    <div class="doc-wrap" style="margin-top:14px">\${docHTML(d,co)}</div>\`;
  $('#print').onclick=()=>window.print();
  const go=async ok=>{const who=$('#who').value.trim(),m=$('#msg');if(ok&&who.length<2){m.hidden=false;m.textContent='Type your name first.';$('#who').focus();return}
    document.querySelectorAll('#respond .btn').forEach(b=>b.disabled=true);
    const {data,error}=await sbc.rpc('respond_shared_doc',{p_token:token,p_name:who,p_approve:ok});
    if(error){m.hidden=false;m.textContent='That didn\\'t go through. Check your connection and try again.';document.querySelectorAll('#respond .btn').forEach(b=>b.disabled=false);return}
    render(data)};
  if($('#approve')){$('#approve').onclick=()=>go(true);$('#decline').onclick=()=>{if(confirm('Decline this estimate?'))go(false)}}}
load();
</script></body></html>
`;
writeFileSync('doc.html', html);
console.log('Built doc.html');
